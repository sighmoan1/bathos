import { test, expect } from '@playwright/test'
import { current, readButton } from './feed-helpers'

test('session deck survives reload, dismissals, tag filters and permalink navigation', async ({ page }) => {
  const labels = () => page.locator('.feed-slide:not(.feed-end) .reader-title').allTextContents()
  await page.goto('/')
  await expect(readButton(page)).toBeVisible()
  const original = await labels()
  const order = await page.evaluate(() => sessionStorage.getItem('swipe-reader-order-v1'))
  expect(JSON.parse(order!)).toHaveLength(original.length)
  await page.reload()
  await expect(readButton(page)).toBeVisible()
  expect(await labels()).toEqual(original)
  await current(page).getByRole('button', { name: 'Bin', exact: true }).click()
  await expect.poll(labels).toEqual(original.slice(1))
  await page.reload()
  await expect(readButton(page)).toBeVisible()
  expect(await labels()).toEqual(original.slice(1))
  await page.evaluate(() => localStorage.setItem('swipe-reader-tags', JSON.stringify(['__no_matching_topic__'])))
  await page.reload()
  await expect(page.getByRole('button', {name: 'Clear filters', exact: true})).toBeVisible()
  await page.getByRole('button', {name: 'Clear filters', exact: true}).click()
  await expect.poll(labels).toEqual(original.slice(1))
  await readButton(page).click()
  const permalink = page.url()
  await page.goto(permalink)
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('swipe-reader-order-v1'))).toBe(order)
})
